"""Train the detectors against the physics model.

Training data is generated by running the mean value engine model over randomised
flight profiles - altitude, ambient temperature and throttle all vary - once with
a healthy engine and once per fault with a degradation injected. Features are
residuals against a *healthy* twin, so the detectors never see absolute values and
cannot simply memorise an operating point.

This is honest about its own limits: the faults are seeded, not observed. What
this validates is that the pipeline separates fault signatures from operating-point
variation. It does not validate against real engine failures, because no public
run-to-failure dataset exists for this engine class.
"""

import numpy as np
import pickle
import os
from mvem import MeanValueEngineModel, Health
from detect import Detector, ResidualWindow, FEATURES, FAULT_LABELS

MODEL_PATH = os.path.join(os.path.dirname(__file__), 'models.pkl')
DT = 0.1
rng = np.random.default_rng(7)

NOISE = {'rpm': 5.0, 'cht_c': 0.9, 'egt_c': 4.5, 'oil_temp_c': 0.5,
         'oil_press_bar': 0.04, 'boost_bar': 0.015, 'fuel_rate_lph': 0.3,
         'vibration_mms': 0.09}


def make_health(fault, sev):
    h = Health()
    if fault == 'injector_underflow':
        h.injector_flow = [1.0] * 4
        h.injector_flow[int(rng.integers(0, 4))] = 1.0 - 0.45 * sev
    elif fault == 'cooling_degradation':
        h.cooling_effectiveness = 1.0 - 0.45 * sev
    elif fault == 'lubrication_loss':
        h.oil_pump_effectiveness = 1.0 - 0.40 * sev
    elif fault == 'turbo_underperformance':
        h.turbo_efficiency = 1.0 - 0.30 * sev
    elif fault == 'combustion_instability':
        h.injector_flow = [1.0 + 0.16 * sev * (1 if i % 2 else -1) for i in range(4)]
        h.ring_seal = 1.0 - 0.06 * sev
    elif fault == 'ring_blowby':
        h.ring_seal = 1.0 - 0.22 * sev
        h.bearing_wear = 0.16 * sev
    return h


def profile(n):
    """A randomised flight segment: climb, cruise or manoeuvre."""
    kind = rng.integers(0, 3)
    alt0 = float(rng.uniform(300, 7000))
    oat = float(rng.uniform(-25, 42))
    t = np.arange(n)
    if kind == 0:      # climb
        alt = alt0 + t * float(rng.uniform(0.2, 0.9))
        thr = np.full(n, float(rng.uniform(0.75, 0.98)))
    elif kind == 1:    # cruise with small corrections
        alt = alt0 + np.cumsum(rng.normal(0, 0.12, n))
        thr = np.clip(float(rng.uniform(0.5, 0.72)) + np.cumsum(rng.normal(0, 0.0016, n)), 0.35, 0.95)
    else:              # throttle transitions
        alt = np.full(n, alt0)
        thr = np.clip(0.6 + 0.3 * np.sin(t / float(rng.uniform(40, 130))), 0.3, 0.98)
    return np.clip(alt, 0, 9400), oat, thr


def run_segment(fault, sev, n=900, warm=260):
    """Returns feature vectors of residuals against a healthy twin."""
    truth = MeanValueEngineModel(); truth.reset()
    twin = MeanValueEngineModel(); twin.reset()
    h = make_health(fault, sev)
    alt, oat, thr = profile(n)
    win = ResidualWindow(size=120)
    vecs = []

    for i in range(n):
        a, th = float(alt[i]), float(thr[i])
        meas = truth.step(DT, th, a, oat, h)
        exp = twin.step(DT, th, a, oat, None, rpm_command=meas['rpm'])
        resid = {}
        for f in FEATURES:
            noisy = meas[f] + rng.normal(0, NOISE[f])
            resid[f] = noisy - exp[f]
        win.push(resid)
        if i >= warm and win.ready() and i % 12 == 0:
            vecs.append(win.feature_vector())
    return vecs


def main():
    healthy, X, y = [], [], []

    print('generating healthy segments')
    for k in range(26):
        v = run_segment('healthy', 0.0)
        healthy += v
        X += v
        y += ['healthy'] * len(v)

    for fault in FAULT_LABELS[1:]:
        print('generating', fault)
        for k in range(14):
            sev = float(rng.uniform(0.45, 1.0))
            v = run_segment(fault, sev)
            X += v
            y += [fault] * len(v)

    healthy = np.asarray(healthy)
    X = np.asarray(X)
    y = np.asarray(y)
    print(f'healthy={healthy.shape}  labelled={X.shape}')

    det = Detector().fit(healthy, X, y)

    # held-out check
    print('\nheld-out check')
    correct = total = 0
    fp = fn = pos = neg = 0
    for fault in FAULT_LABELS:
        for _ in range(4):
            sev = 0.0 if fault == 'healthy' else float(rng.uniform(0.5, 1.0))
            v = run_segment(fault, sev)
            if not v:
                continue
            x = v[len(v) // 2]
            pred, conf, _ = det.classify(x)
            anom, _sev = det.anomaly(x)
            correct += int(pred == fault); total += 1
            if fault == 'healthy':
                neg += 1; fp += int(anom)
            else:
                pos += 1; fn += int(not anom)
    print(f'  classifier accuracy {correct}/{total}')
    print(f'  anomaly false positives {fp}/{neg}, misses {fn}/{pos}')

    with open(MODEL_PATH, 'wb') as f:
        pickle.dump(det, f)
    print(f'\nsaved {MODEL_PATH}')


if __name__ == '__main__':
    main()
